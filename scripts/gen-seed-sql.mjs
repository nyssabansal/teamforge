// Generates db/sql/04_seed.sql from db/seed/data.mjs
// Usage: node scripts/gen-seed-sql.mjs
import { writeFileSync } from 'node:fs';
import * as d from '../db/seed/data.mjs';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const uid = (h) => `(SELECT user_id FROM users WHERE email = ${q(`${h}@teamforge.dev`)})`;
const sid = (n) => `(SELECT skill_id FROM skills WHERE name = ${q(n)})`;
const eid = (k) => `(SELECT event_id FROM events WHERE title = ${q(d.events.find((e) => e.key === k).title)})`;
const tid = (n) => `(SELECT team_id FROM teams WHERE team_name = ${q(n)})`;

const out = [];
const p = (s = '') => out.push(s);

p('-- =====================================================================');
p('-- 04_seed.sql — demo data (GENERATED by scripts/gen-seed-sql.mjs)');
p('-- Every account password: password123  (stored only as a bcrypt hash)');
p('-- =====================================================================');
p('BEGIN;');
p("-- allow loading a completed (past) event; triggers check this setting");
p("SET LOCAL app.bypass_deadline = 'on';");
p();
p('-- skills');
p('INSERT INTO skills (name, category) VALUES');
p(d.skills.map(([n, c]) => `  (${q(n)}, ${q(c)})`).join(',\n') + ';');
p();
p('-- users');
const allUsers = [
  ...d.staff.map(([name, h, role]) => [name, h, role]),
  ...d.participants.map((x) => [x.name, x.handle, 'participant']),
];
p('INSERT INTO users (name, email, password_hash, role) VALUES');
p(allUsers.map(([n, h, r]) => `  (${q(n)}, ${q(`${h}@teamforge.dev`)}, ${q(d.PASSWORD_HASH)}, ${q(r)})`).join(',\n') + ';');
p();
p('-- user skills');
p('INSERT INTO user_skills (user_id, skill_id, proficiency) VALUES');
p(d.participants.flatMap((x) => Object.entries(x.skills).map(([s, lvl]) => `  (${uid(x.handle)}, ${sid(s)}, ${lvl})`)).join(',\n') + ';');
p();
p('-- events');
for (const e of d.events) {
  p(`INSERT INTO events (organizer_id, title, description, theme, venue, start_date, end_date, reg_deadline, min_team_size, max_team_size, status)
VALUES (${uid(e.organizer)}, ${q(e.title)}, ${q(e.description)}, ${q(e.theme)}, ${q(e.venue)}, ${q(e.start)}, ${q(e.end)}, ${q(e.deadline)}, ${e.min}, ${e.max}, ${q(e.status)});`);
}
p();
p('-- judges');
for (const [ek, js] of Object.entries(d.judgesByEvent))
  for (const j of js) p(`INSERT INTO event_judges (event_id, judge_id) VALUES (${eid(ek)}, ${uid(j)});`);
p();
p('-- registrations');
for (const [ek, hs] of Object.entries(d.registrations))
  for (const h of hs) p(`INSERT INTO registrations (event_id, user_id) VALUES (${eid(ek)}, ${uid(h)});`);
p();
p('-- teams (sp_create_team makes the leader the first member), then required skills and members');
for (const t of d.teams) {
  // CALL can't take subqueries as arguments, so resolve ids in a DO block first
  p(`DO $$ DECLARE v_event INT := ${eid(t.event)}; v_leader INT := ${uid(t.leader)}; v_team INT;
BEGIN CALL sp_create_team(v_event, v_leader, ${q(t.name)}, ${q(t.pitch)}, ${t.capacity}, v_team); END $$;`);
  for (const [s, lvl] of Object.entries(t.required))
    p(`INSERT INTO team_required_skills (team_id, skill_id, min_proficiency) VALUES (${tid(t.name)}, ${sid(s)}, ${lvl});`);
  for (const m of t.members)
    p(`INSERT INTO team_members (team_id, user_id, event_id) VALUES (${tid(t.name)}, ${uid(m)}, ${eid(t.event)});`);
}
p();
p('-- pending join requests');
for (const r of d.joinRequests)
  p(`INSERT INTO join_requests (team_id, user_id, message) VALUES (${tid(r.team)}, ${uid(r.user)}, ${q(r.message)});`);
p();
p('-- submissions and scores (completed event)');
for (const s of d.submissions)
  p(`INSERT INTO submissions (team_id, project_title, summary, repo_url) VALUES (${tid(s.team)}, ${q(s.title)}, ${q(s.summary)}, ${q(s.repo)});`);
const crit = ['innovation', 'technical', 'design', 'impact', 'presentation'];
for (const [team, byJudge] of Object.entries(d.scores))
  for (const [j, vals] of Object.entries(byJudge))
    vals.forEach((v, i) =>
      p(`INSERT INTO scores (submission_id, judge_id, criterion, score) VALUES ((SELECT submission_id FROM submissions WHERE team_id = ${tid(team)}), ${uid(j)}, ${q(crit[i])}, ${v});`));
p();
p('REFRESH MATERIALIZED VIEW mv_skill_demand;');
p('COMMIT;');

writeFileSync(new URL('../db/sql/04_seed.sql', import.meta.url), out.join('\n') + '\n');
console.log(`wrote db/sql/04_seed.sql (${out.length} lines)`);
